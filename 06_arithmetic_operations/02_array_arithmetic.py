import numpy as np

a = np.array([10, 20, 30, 40])
b = np.array([2, 4, 5, 10])

print("Array A:", a)
print("Array B:", b)

print("\nAddition:")
print(a + b)

print("\nSubtraction:")
print(a - b)

print("\nMultiplication:")
print(a * b)

print("\nDivision:")
print(a / b)

print("\nFloor Division:")
print(a // b)

print("\nModulus:")
print(a % b)

print("\nPower:")
print(a ** b)

